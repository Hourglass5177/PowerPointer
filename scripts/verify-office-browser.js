async page => {
  const check=(condition,message)=>{if(!condition)throw Error(message);};
  await page.getByRole('button',{name:'第4页',exact:true}).click();
  check(await page.getByRole('textbox',{name:'页码',exact:true}).inputValue()==='4','citation jump');
  await page.getByRole('button',{name:'跳到第 3 页',exact:true}).click();
  await page.getByRole('region',{name:'课件阅读区'}).focus();await page.keyboard.press('PageUp');
  check(await page.getByRole('textbox',{name:'页码',exact:true}).inputValue()==='2','PageUp navigation');
  await page.getByRole('textbox',{name:'向课件提问'}).fill('keyboard check');await page.keyboard.press('ArrowLeft');
  check(await page.getByRole('textbox',{name:'页码',exact:true}).inputValue()==='2','input must not navigate');await page.getByRole('textbox',{name:'向课件提问'}).fill('');
  await page.getByRole('button',{name:'搜索',exact:true}).click();
  await page.getByRole('textbox',{name:'全文搜索'}).fill('白鹭');await page.getByRole('textbox',{name:'全文搜索'}).press('Enter');
  await page.getByRole('button',{name:/第 3 页.*隐藏页/s}).waitFor();
  await page.getByRole('button',{name:/第 3 页.*隐藏页/s}).click();
  check(await page.getByRole('textbox',{name:'页码',exact:true}).inputValue()==='3','hidden slide text search');
  await page.getByRole('button',{name:'搜索',exact:true}).first().click();
  await page.getByRole('button',{name:'跳到第 1 页',exact:true}).click();
  await page.getByTestId('pdf-page').locator('.textLayer').getByText('导数：函数在一点的变化率',{exact:true}).waitFor();
  const word=page.getByTestId('pdf-page').locator('.textLayer').getByText('导数：函数在一点的变化率',{exact:true});
  const b=await word.boundingBox();check(b,'selection text bounds');
  await page.mouse.move(b.x+2,b.y+b.height/2);await page.mouse.down();await page.mouse.move(b.x+b.width-2,b.y+b.height/2,{steps:15});await page.mouse.up();
  await page.getByRole('textbox',{name:'向课件提问'}).focus();
  check(await page.getByRole('button',{name:/选中文字/}).isVisible(),'text selection retained after focus');
  await page.getByRole('button',{name:/选中文字/}).click();
  await page.getByRole('button',{name:'跳到第 4 页',exact:true}).click();
  await page.getByRole('button',{name:'旋转',exact:true}).click();
  await page.getByRole('slider',{name:'缩放滑块'}).evaluate(el=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'150');el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));});
  await page.waitForFunction(()=>document.querySelector('[aria-label="缩放滑块"]').value==='150');
  await page.getByTestId('page-scroll').evaluate(el=>{el.scrollTop=160;});
  await page.getByRole('button',{name:'框选',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.rendering'));
  const canvas=await page.getByTestId('pdf-page').boundingBox();
  const scale=canvas.width/540;
  await page.mouse.move(canvas.x+185*scale,canvas.y+125*scale);await page.mouse.down();await page.mouse.move(canvas.x+295*scale,canvas.y+230*scale,{steps:15});await page.mouse.up();
  check(await page.getByRole('textbox',{name:'向课件提问'}).evaluate(el=>el===document.activeElement),'crop focuses composer');
  check(await page.getByRole('button',{name:/框选区域/}).isVisible(),'crop chip visible');
  let submitted;
  await page.route('**/api/turns',async route=>{submitted=route.request().postDataJSON();await route.fulfill({status:429,contentType:'application/json',body:JSON.stringify({error:'受控验收：额度错误'})});});
  await page.getByRole('textbox',{name:'向课件提问'}).fill('受控验收：只验证框选快照');await page.getByRole('textbox',{name:'向课件提问'}).press('Control+Enter');
  await page.getByRole('alert').waitFor();
  check(submitted?.snapshot.rotation===90&&submitted.snapshot.page===4,'rotated crop snapshot');
  const expected=[125,185,230,295];check(submitted.snapshot.rect.every((n,i)=>Math.abs(n-expected[i])<1),'crop coordinates');
  await page.screenshot({path:'output/playwright/office-crop-150-rotation.png'});
  await page.unroute('**/api/turns');await page.getByRole('button',{name:'关闭提示'}).click();await page.getByRole('button',{name:/框选区域/}).click();await page.getByRole('textbox',{name:'向课件提问'}).fill('');
  for(let i=0;i<3;i++)await page.getByRole('button',{name:'旋转',exact:true}).click();await page.getByRole('button',{name:'适合页面',exact:true}).click();
  return {citation:true,keyboard:true,searchHiddenPage:true,textSelection:true,crop:submitted.snapshot,controlledError:true};
}
